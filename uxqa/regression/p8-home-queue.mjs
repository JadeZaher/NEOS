import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
process.env.UXQA_STUDY_DIR=path.resolve('uxqa');
const {uxSession,BASE}=await import(pathToFileURL(path.join(process.env.UXQA_PLUGIN_ROOT || 'C:/Users/atooz/.claude/plugins/cache/local/ux-qa-research/0.1.0', 'lib/ux-lib.mjs')).href);
assert.ok(['localhost','127.0.0.1'].includes(new URL(BASE).hostname));
const out=path.resolve('uxqa/passes/08-community-engagement');
const s=await uxSession({handle:'qa-member-ines',task:'p8-home-queue-disclosure',pass:'08-community-engagement',mode:'probe'});
const report={outcome:'FAILED',checks:[]};
let failure;
try{
 await s.page.goto(BASE+'/dashboard',{waitUntil:'networkidle'});
 assert.equal((await s.request('GET','/api/v1/settings/?key=uxqa_environment')).body.value.db,'neos_uxqa');
 assert.equal((await s.request('GET','/api/v1/engagement/capabilities')).body.external_delivery_enabled,false);
 const queue=(await s.request('GET','/api/v1/me/next-steps')).body;
 assert.ok(queue.items.length>5,'Need actual long queue fixture');
 const total=queue.items.length;
 const list=s.page.locator('#home-next-steps');
 await list.waitFor();
 assert.equal(await list.locator('li').count(),5);
 await s.page.getByText(`Showing 5 of ${total} next steps.`,{exact:true}).waitFor();
 await s.page.getByLabel(`${queue.count} pending actions`,{exact:true}).waitFor();
 const firstLinks=await list.locator('a').evaluateAll(links=>links.map(link=>link.getAttribute('href')));
 const expand=s.page.getByRole('button',{name:`Show all ${total} next steps`,exact:true});
 assert.equal(await expand.getAttribute('aria-expanded'),'false');
 assert.equal(await expand.getAttribute('aria-controls'),'home-next-steps');
 const activity=s.page.getByRole('heading',{name:'Recent community activity',exact:true});
 const collapsedTop=await activity.evaluate(el=>el.getBoundingClientRect().top+window.scrollY);
 await s.page.screenshot({path:path.join(out,'engagement-dashboard-bounded-desktop.png'),fullPage:true});
 await expand.focus();
 await s.page.keyboard.press('Enter');
 assert.equal(await list.locator('li').count(),total);
 const expandedLinks=await list.locator('a').evaluateAll(links=>links.map(link=>link.getAttribute('href')));
 assert.deepEqual(expandedLinks.slice(0,5),firstLinks);
 assert.deepEqual(expandedLinks,[...queue.items].sort((a,b)=>Number(String(b.kind)==='newcomer')-Number(String(a.kind)==='newcomer')).map(item=>item.link));
 const collapse=s.page.getByRole('button',{name:'Show fewer',exact:true});
 assert.equal(await collapse.getAttribute('aria-expanded'),'true');
 const expandedTop=await activity.evaluate(el=>el.getBoundingClientRect().top+window.scrollY);
 await collapse.focus();
 await s.page.keyboard.press('Enter');
 assert.equal(await list.locator('li').count(),5);
 assert.equal(await expand.getAttribute('aria-expanded'),'false');
 assert.equal(await expand.evaluate(el=>document.activeElement===el),true);
 assert.ok(expandedTop-collapsedTop>1000);
 await activity.scrollIntoViewIfNeeded();
 await s.page.screenshot({path:path.join(out,'engagement-home-activity-discoverability.png')});
 report.outcome='COMPLETED';
 report.totalNextSteps=total;
 report.communityActivityTop={collapsed:collapsedTop,expanded:expandedTop};
 report.checks=['Five initial next steps with preserved full count','Keyboard expand and collapse with truthful aria-expanded and retained focus','Every ordered action link preserved when expanded','Community activity follows bounded queue'];
}catch(error){failure=error;report.error=String(error.stack||error);}
finally{fs.writeFileSync(path.join(out,'engagement-home-queue-regression.json'),JSON.stringify(report,null,2));await s.finish(report.outcome,'Read-only browser keyboard disclosure check; no product records changed.');}
if(failure)throw failure;
console.log('GREEN engagement-home-queue-disclosure');
